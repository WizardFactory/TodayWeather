#!/usr/bin/env python3
"""Generate the instance boot configuration for the server2 log pipeline (LP-3, #2980).

The output is one shell script for EC2 user data (cloud-init runs it once, as root, at
the first boot). It names one commit of this repository and the SHA-256 of every
pipeline file at that commit, downloads the files from that commit and refuses any file
whose hash differs, writes the destination settings as a drop-in for the collector unit,
runs install.sh (which downloads the pinned collector and checks its SHA-256) and starts
the collector. No SSH step and no AWS key: the collector takes credentials from the
instance role. Every instance uses the same output; nothing in it is instance-specific.

  python3 -I boot.py --revision COMMIT --sinks local,s3,cloudwatch --prefix logs/server2 \\
      --group /server2/production --bucket BUCKET --region ap-northeast-2 --out DIR

COMMIT must be a commit that is on GitHub (for example the merged master commit), and the
pipeline files in this checkout must equal the files at that commit, so the settings are
validated by the same code the instance will run. Writes DIR/user-data.sh and
DIR/user-data.sh.gz (cloud-init accepts gzip; EC2 limits user data to 16 KiB, checked
here). The server2 binary and its .env still come from the release procedure; the server
unit is enabled and starts once they are present.
"""
import argparse
import gzip
import hashlib
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import render  # noqa: E402

# The files a host needs; checks and stand-ins stay out of user data.
BUNDLE = ('install.sh', 'render.py', 'status.py', 'collector.json', 'units/server2.service',
          'units/server2-logs.service', 'units/server2-logs-status.service', 'units/server2-logs-status.timer',
          'units/journald@server2.conf', 'units/journald-system.conf')
REPOSITORY = 'https://raw.githubusercontent.com/WizardFactory/TodayWeather'
PATH_IN_REPOSITORY = 'server2/deploy/logging'
EC2_USER_DATA_LIMIT = 16 * 1024


class BootError(Exception):
    pass


def drop_in(config):
    """Collector-unit environment from the validated settings only. Every value matches
    render.settings' character rules, so none needs systemd quoting or "%" escaping, and a
    setting the selected destinations do not use is not written at all."""
    remote = [d for d in config['sinks'] if d != 'local']
    values = {'SERVER2_LOG_SINKS': ','.join(config['sinks']),
              'SERVER2_LOG_S3_LEVEL': config['s3_level'] if 's3' in remote else None,
              'SERVER2_LOG_CLOUDWATCH_LEVEL': config['cloudwatch_level'] if 'cloudwatch' in remote else None,
              'SERVER2_S3_REGION': config.get('region'), 'SERVER2_S3_BUCKET': config.get('bucket'),
              'SERVER2_LOG_S3_PREFIX': config.get('prefix'), 'SERVER2_LOG_CLOUDWATCH_GROUP': config.get('group')}
    lines = ['[Service]', '# Destination settings from the boot configuration; they take precedence over .env.']
    for name in render.ALLOWED:
        value = values.get(name)
        if value:
            assert re.fullmatch(r'[A-Za-z0-9._/#,-]+', value), name
            lines.append(f'Environment="{name}={value}"')
    return '\n'.join(lines) + '\n'


def script(values, revision, digests, repository=REPOSITORY):
    """The user-data script for the validated destination settings, the commit and the
    SHA-256 of each bundle file at that commit."""
    config = render.settings(values)  # the collector's own validation, before anything is generated
    if not re.fullmatch(r'[0-9a-f]{40}', revision):
        raise BootError('the revision must be a full 40-digit commit ID')
    if set(digests) != set(BUNDLE) or not all(re.fullmatch(r'[0-9a-f]{64}', d) for d in digests.values()):
        raise BootError('a SHA-256 is needed for every bundle file')
    parts = ['#!/bin/bash',
             '# server2 log pipeline boot configuration (generated by server2/deploy/logging/boot.py).',
             '# Runs once as root at first boot; no SSH, no AWS keys (instance role).',
             'set -euo pipefail', 'umask 022',
             f'base={repository}/{revision}/{PATH_IN_REPOSITORY}',
             'bundle=$(mktemp -d)', 'trap \'rm -rf "$bundle"\' EXIT', 'mkdir -p "$bundle/units"',
             'fetch() {',
             '  curl --fail --silent --show-error --location --proto \'=https\' --retry 5 --retry-all-errors \\',
             '    --max-time 60 -o "$bundle/$1" "$base/$1"',
             '  echo "$2  $bundle/$1" | sha256sum --check --status || { echo "server2 log pipeline: $1 hash mismatch" >&2; exit 1; }',
             '}']
    parts += [f'fetch {name} {digests[name]}' for name in BUNDLE]
    parts += ['install -d -m 0755 /etc/systemd/system/server2-logs.service.d',
              "cat > /etc/systemd/system/server2-logs.service.d/destinations.conf <<'SERVER2_DESTINATIONS'",
              drop_in(config) + 'SERVER2_DESTINATIONS',
              'bash "$bundle/install.sh"',
              '# The collector starts now and at every boot; it ships from its first record.',
              'systemctl start server2-logs.service || true',
              f'echo "server2 log pipeline: boot configuration applied ({revision[:12]})"']
    return '\n'.join(parts) + '\n'


def revision_digests(revision, run=subprocess.run):
    """Full commit ID and the SHA-256 of each bundle file at that commit; the files in this
    checkout must be identical, so validation and the instance run the same code."""
    def git(*arguments):
        result = run(['git', '-C', str(HERE), *arguments], capture_output=True)
        if result.returncode != 0:
            raise BootError(f'git {arguments[0]} failed for revision {revision}')
        return result.stdout
    commit = git('rev-parse', '--verify', f'{revision}^{{commit}}').decode().strip()
    digests, changed = {}, []
    for name in BUNDLE:
        content = git('show', f'{commit}:{PATH_IN_REPOSITORY}/{name}')
        digests[name] = hashlib.sha256(content).hexdigest()
        if (HERE / name).read_bytes() != content:
            changed.append(name)
    if changed:
        raise BootError('these files differ from the revision (commit and push first): ' + ', '.join(changed))
    return commit, digests


def main(argv=None, digests_for=revision_digests):
    parser = argparse.ArgumentParser(description='Generate the server2 log pipeline boot configuration.')
    parser.add_argument('--revision', required=True, help='a commit on GitHub, e.g. the merged master commit')
    parser.add_argument('--sinks', required=True)
    parser.add_argument('--s3-level', default='info')
    parser.add_argument('--cloudwatch-level', default='warn')
    parser.add_argument('--prefix', default='')
    parser.add_argument('--group', default='')
    parser.add_argument('--bucket', default='')
    parser.add_argument('--region', default='')
    parser.add_argument('--out', required=True, help='new directory')
    args = parser.parse_args(argv)
    values = {'SERVER2_LOG_SINKS': args.sinks, 'SERVER2_LOG_S3_LEVEL': args.s3_level,
              'SERVER2_LOG_CLOUDWATCH_LEVEL': args.cloudwatch_level, 'SERVER2_LOG_S3_PREFIX': args.prefix,
              'SERVER2_LOG_CLOUDWATCH_GROUP': args.group, 'SERVER2_S3_BUCKET': args.bucket, 'SERVER2_S3_REGION': args.region}
    try:
        render.settings(values)
        commit, digests = digests_for(args.revision)
        text = script(values, commit, digests)
    except render.SettingError as exc:
        print(f'boot.py: invalid setting {exc}', file=sys.stderr)
        return 2
    except BootError as exc:
        print(f'boot.py: {exc}', file=sys.stderr)
        return 2
    compressed = gzip.compress(text.encode(), compresslevel=9, mtime=0)
    if len(compressed) > EC2_USER_DATA_LIMIT:
        print(f'boot.py: compressed user data is {len(compressed)} bytes, above the EC2 limit', file=sys.stderr)
        return 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=False)
    (out / 'user-data.sh').write_text(text)
    (out / 'user-data.sh.gz').write_bytes(compressed)
    print(f'boot.py: revision {commit}; user-data.sh {len(text.encode())} bytes, '
          f'user-data.sh.gz {len(compressed)} bytes (EC2 limit {EC2_USER_DATA_LIMIT})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
