#!/usr/bin/env python3
"""Copy the Cordova client's images, translations and town list into the Android app.

The Android build never reads client/; this tool is the only bridge. It is deterministic:
re-running it without changes in client/ leaves android/ unchanged.

Outputs (paths relative to android/app/):
  src/main/assets/img/**             copies of client/www/img/**/*.png
  src/main/assets/data/towns.json    client/www/data/town.js without its `window.towns=` prefix
  src/main/res/values*/client_strings.xml  client/www/locales/*.json as string resources
  src/main/res/font/material_icons.ttf  client/www/fonts/MaterialIcons-Regular.ttf
  src/main/res/mipmap-*/ic_launcher.png   client/tw.resources/android/icon/drawable-*-icon.png (launcher icon)
  src/main/res/drawable-nodpi/splash_icon.png  client/tw.resources/android-launcher-icon.png (Android 12+ splash)
  provenance/client-assets.json      source path, last commit, and hashes for every output

Usage: python3 android/tools/import_client_assets.py   (from anywhere inside the repository)
"""
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
CLIENT = ROOT / "client" / "www"
# The TodayWeather build resources that client/config.xml names (`tw.resources/...`).
TW_RESOURCES = ROOT / "client" / "tw.resources"
ICON_DENSITIES = ["ldpi", "mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"]
APP = ROOT / "android" / "app"
ASSETS = APP / "src" / "main" / "assets"
RES = APP / "src" / "main" / "res"
PROVENANCE = APP / "provenance" / "client-assets.json"

# Cordova registers these catalogs and falls back to English (client/www/js/app.js).
LOCALE_DIRS = {
    "en": "values",
    "ko": "values-ko",
    "ja": "values-ja",
    "de": "values-de",
    "zh-CN": "values-zh-rCN",
    "zh-TW": "values-zh-rTW",
}
KEY = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
RENAMED = {}  # catalog key -> resource name, for keys that are not valid resource names


def resource_name(key: str) -> str:
    """Catalog keys such as `LOC_TODAY_THAN_YESTERDAY?` become `LOC_TODAY_THAN_YESTERDAY_`."""
    name = re.sub(r"[^A-Za-z0-9_]", "_", key)
    if not KEY.match(name):
        sys.exit(f"unsupported catalog key {key!r}")
    if name != key:
        RENAMED[key] = name
    return name


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def last_commits(paths):
    """Last commit that touched each path, from one `git log` walk."""
    wanted = {p.relative_to(ROOT).as_posix() for p in paths}
    found = {}
    log = subprocess.run(
        ["git", "-C", str(ROOT), "log", "--format=@%H", "--name-only", "--", "client/www/img",
         "client/www/locales", "client/www/data/town.js", "client/www/fonts/MaterialIcons-Regular.ttf",
         "client/tw.resources/android/icon", "client/tw.resources/android-launcher-icon.png"],
        check=True, capture_output=True, text=True).stdout
    commit = None
    for line in log.splitlines():
        if line.startswith("@"):
            commit = line[1:]
        elif line in wanted and line not in found:
            found[line] = commit
    missing = wanted - found.keys()
    if missing:
        sys.exit(f"no commit found for {sorted(missing)[:3]} (needs full history and committed sources)")
    return found


def android_string(value: str) -> str:
    """Escape a catalog value for an Android string resource; the text stays literal."""
    value = value.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if value[:1] in ("@", "?"):
        value = "\\" + value
    return escape(value)


def strings_xml(catalog: dict) -> bytes:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by android/tools/import_client_assets.py; do not edit. -->",
             "<resources>"]
    names = {}
    for key in sorted(catalog):
        if not isinstance(catalog[key], str):
            sys.exit(f"unsupported catalog entry {key!r}")
        name = resource_name(key)
        if names.setdefault(name, key) != key:
            sys.exit(f"keys {names[name]!r} and {key!r} map to the same resource name")
        lines.append(f'    <string name="{name}" formatted="false">{android_string(catalog[key])}</string>')
    lines.append("</resources>")
    return ("\n".join(lines) + "\n").encode("utf-8")


SKIPPED = []  # tracked duplicates that differ from a kept file only by letter case


def tracked_images():
    """Tracked PNGs from Git, not the file system: case-insensitive checkouts (macOS) hide
    `client/www/img/KR.png`, a same-content duplicate of the `kr.png` the app references."""
    rows = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-s", "-z", "--", "client/www/img"],
                          check=True, capture_output=True, text=True).stdout.split("\0")
    groups = {}
    for row in filter(None, rows):
        meta, path = row.split("\t", 1)
        if path.endswith(".png"):
            groups.setdefault(path.lower(), []).append((path, meta.split()[1]))
    images = []
    for key, entries in sorted(groups.items()):
        if len(entries) > 1:
            keep = [e for e in entries if e[0] == key]
            if not keep or len({blob for _, blob in entries}) != 1:
                sys.exit(f"case-insensitive name collision with different content: {entries}")
            SKIPPED.extend(sorted(path for path, _ in entries if path != key))
            entries = keep
        images.append(ROOT / entries[0][0])
    return sorted(images)


def main():
    images = tracked_images()
    town = CLIENT / "data" / "town.js"
    locales = [CLIENT / "locales" / f"{code}.json" for code in LOCALE_DIRS]
    material_icons = CLIENT / "fonts" / "MaterialIcons-Regular.ttf"
    launcher_icons = [TW_RESOURCES / "android" / "icon" / f"drawable-{d}-icon.png" for d in ICON_DENSITIES]
    splash_icon = TW_RESOURCES / "android-launcher-icon.png"
    commits = last_commits(images + [town] + locales + [material_icons] + launcher_icons + [splash_icon])

    outputs = []  # (source, output, data)
    for src in images:
        outputs.append((src, ASSETS / "img" / src.relative_to(CLIENT / "img"), src.read_bytes()))

    text = town.read_text(encoding="utf-8").strip()
    prefix = "window.towns="
    if not text.startswith(prefix):
        sys.exit("unexpected town.js format")
    towns = json.loads(text[len(prefix):].rstrip(";"))
    data = (json.dumps(towns, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    outputs.append((town, ASSETS / "data" / "towns.json", data))

    for code, src in zip(LOCALE_DIRS, locales):
        catalog = json.loads(src.read_text(encoding="utf-8"))
        outputs.append((src, RES / LOCALE_DIRS[code] / "client_strings.xml", strings_xml(catalog)))

    # The Material Icons font of the Cordova app (location and expander glyphs).
    outputs.append((material_icons, RES / "font" / "material_icons.ttf", material_icons.read_bytes()))

    # The launcher icon and the Android 12+ splash icon of the Cordova build (config.xml <icon>,
    # AndroidWindowSplashScreenAnimatedIcon), so the home screen and the launch look the same after the update.
    for density, src in zip(ICON_DENSITIES, launcher_icons):
        outputs.append((src, RES / f"mipmap-{density}" / "ic_launcher.png", src.read_bytes()))
    outputs.append((splash_icon, RES / "drawable-nodpi" / "splash_icon.png", splash_icon.read_bytes()))

    # Replace the generated trees so files removed from client/ disappear here too.
    shutil.rmtree(ASSETS / "img", ignore_errors=True)
    records = []
    for src, out, data in outputs:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
        rel_src = src.relative_to(ROOT).as_posix()
        records.append({
            "source": rel_src,
            "commit": commits[rel_src],
            "source_sha256": sha256(src.read_bytes()),
            "output": out.relative_to(APP).as_posix(),
            "output_sha256": sha256(data),
        })
    records.sort(key=lambda r: r["output"])
    PROVENANCE.parent.mkdir(parents=True, exist_ok=True)
    PROVENANCE.write_text(json.dumps({
        "tool": "android/tools/import_client_assets.py",
        "license": "Same repository and license as client/ (TodayWeather, WizardFactory), except res/font/material_icons.ttf: Material Icons, Apache License 2.0 (Google)",
        "renamed_string_keys": dict(sorted(RENAMED.items())),
        "skipped_case_duplicates": SKIPPED,
        "files": records,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"imported {len(records)} files; provenance in {PROVENANCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
