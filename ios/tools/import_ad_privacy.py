#!/usr/bin/env python3
"""Copies the Cordova iOS build's tracking purpose strings and AdMob Info.plist entries into ios/ (IN-15, #2964).

    python3 ios/tools/import_ad_privacy.py [--plugin-tarball PATH]

- The localized NSUserTrackingUsageDescription (#2945): client/resources/ios/tracking/<locale>.lproj/InfoPlist.strings,
  the folders client/config.xml copies into the Cordova app, byte for byte to ios/TodayWeather/<locale>.lproj/.
  The English text also goes into ios/Support/Info.plist, as client/scripts/ios-ad-privacy.js writes it into
  App-Info.plist.
- The Info.plist entries the AdMob plugin adds to the Cordova build (emi-indo-cordova-plugin-admob, the version and
  integrity pinned by client/package-lock.json): GADDelayAppMeasurementInit and SKAdNetworkItems from the plugin's
  plugin.xml. The tool downloads the locked tarball from the npm registry (or reads --plugin-tarball) and refuses it
  unless its SHA-512 equals the lock file's integrity.

The generated part of ios/Support/Info.plist sits between two marker comments; the rest of the file is kept.
ios/provenance/ad-privacy.json records every source's path, last commit and SHA-256, the plugin's version,
integrity and plugin.xml hash, and the imported values. Only this tool reads client/; the iOS build reads the copies.
Running it again without source changes changes nothing (CI checks that).
"""
import argparse
import base64
import hashlib
import io
import json
import re
import subprocess
import sys
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
IOS = ROOT / "ios"
LOCALES = ["ko", "en", "ja", "zh-Hans", "zh-Hant"]
TRACKING = "client/resources/ios/tracking"
CONFIG = "client/config.xml"
LOCK = "client/package-lock.json"
PLUGIN = "emi-indo-cordova-plugin-admob"
KEY = "NSUserTrackingUsageDescription"
INFO = IOS / "Support" / "Info.plist"
PROVENANCE = IOS / "provenance" / "ad-privacy.json"
BEGIN = "\t<!-- BEGIN generated by ios/tools/import_ad_privacy.py (provenance/ad-privacy.json); do not edit -->\n"
END = "\t<!-- END generated by ios/tools/import_ad_privacy.py -->\n"


def git(*args) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True).stdout.strip()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def commit_of(path: str) -> str:
    commit = git("log", "-1", "--format=%H", "--", path)
    if not commit:
        sys.exit(f"no commit for {path}: the tool needs the Git history")
    return commit


def strings_value(path: Path) -> str:
    """The purpose string of an InfoPlist.strings file, parsed by plutil as iOS reads it."""
    out = subprocess.run(["plutil", "-convert", "json", "-o", "-", str(path)], check=True, capture_output=True).stdout
    table = json.loads(out)
    if set(table) != {KEY} or not isinstance(table[KEY], str) or not table[KEY].strip():
        sys.exit(f"{path.relative_to(ROOT)}: expected exactly one non-empty {KEY}")
    return table[KEY]


def check_config():
    """config.xml copies exactly these locale folders into the Cordova app."""
    text = (ROOT / CONFIG).read_text(encoding="utf-8")
    found = re.findall(r'<resource-file src="resources/ios/tracking/([^"]+)\.lproj" target="([^"]+)\.lproj" />', text)
    if sorted(found) != sorted((l, l) for l in LOCALES):
        sys.exit(f"{CONFIG} lists other tracking folders than {LOCALES}: {found}")


def plugin_lock():
    lock = json.loads((ROOT / LOCK).read_text(encoding="utf-8"))
    entry = lock["packages"].get(f"node_modules/{PLUGIN}")
    if not entry or not entry.get("integrity", "").startswith("sha512-"):
        sys.exit(f"{LOCK} has no sha512 integrity for {PLUGIN}")
    return entry


def plugin_xml(entry, tarball) -> bytes:
    data = tarball.read_bytes() if tarball else urllib.request.urlopen(entry["resolved"], timeout=60).read()
    digest = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if digest != entry["integrity"]:
        sys.exit(f"the {PLUGIN} tarball does not match {LOCK} ({digest} != {entry['integrity']})")
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        member = tar.extractfile("package/plugin.xml")
        if member is None:
            sys.exit("the plugin tarball has no package/plugin.xml")
        return member.read()


def plugin_entries(xml: bytes):
    """GADDelayAppMeasurementInit and the SKAdNetwork identifiers of the plugin's iOS Info.plist entries."""
    root = ET.fromstring(xml)
    ns = {"p": "http://apache.org/cordova/ns/plugins/1.0"}
    ios = root.find("p:platform[@name='ios']", ns)
    if ios is None:
        sys.exit("plugin.xml has no iOS platform")
    entries = {c.get("parent"): c for c in ios.findall("p:config-file", ns) if c.get("target") == "*-Info.plist"}
    expected = {"GADApplicationIdentifier", KEY, "GADDelayAppMeasurementInit", "SKAdNetworkItems"}
    if set(entries) != expected:
        sys.exit(f"plugin.xml's Info.plist entries changed: {sorted(entries)}; review them before importing")
    delay = entries["GADDelayAppMeasurementInit"]
    if [child.tag.split("}")[-1] for child in delay] != ["true"]:
        sys.exit("plugin.xml's GADDelayAppMeasurementInit is not <true/>")
    ids = []
    for item in entries["SKAdNetworkItems"].iter():
        if item.tag.split("}")[-1] == "dict":
            parts = [(c.tag.split("}")[-1], (c.text or "").strip()) for c in item]
            if len(parts) != 2 or parts[0] != ("key", "SKAdNetworkIdentifier") or parts[1][0] != "string":
                sys.exit(f"unexpected SKAdNetworkItems entry {parts}")
            ids.append(parts[1][1])
    if not ids or len(set(ids)) != len(ids) or not all(re.fullmatch(r"[a-z0-9]+\.skadnetwork", i) for i in ids):
        sys.exit(f"unexpected SKAdNetwork identifiers: {ids}")
    return ids


def info_block(english: str, ids) -> str:
    lines = [BEGIN,
             "\t<!-- The English tracking purpose string of the Cordova build (client/scripts/ios-ad-privacy.js);\n"
             "\t     the localized ones are in TodayWeather/<locale>.lproj/InfoPlist.strings. -->\n",
             f"\t<key>{KEY}</key>\n", f"\t<string>{escape(english)}</string>\n",
             f"\t<!-- The AdMob plugin's entries ({PLUGIN}, plugin.xml). -->\n",
             "\t<key>GADDelayAppMeasurementInit</key>\n", "\t<true/>\n",
             "\t<key>SKAdNetworkItems</key>\n", "\t<array>\n"]
    for i in ids:
        lines += ["\t\t<dict>\n", "\t\t\t<key>SKAdNetworkIdentifier</key>\n", f"\t\t\t<string>{i}</string>\n",
                  "\t\t</dict>\n"]
    lines += ["\t</array>\n", END]
    return "".join(lines)


def write(path: Path, data: bytes, changed: list):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    changed.append(str(path.relative_to(ROOT)))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--plugin-tarball", type=Path, help="the plugin tarball instead of downloading it")
    args = parser.parse_args()
    check_config()
    changed = []
    locales = []
    for locale in LOCALES:
        src = f"{TRACKING}/{locale}.lproj/InfoPlist.strings"
        data = (ROOT / src).read_bytes()
        out = IOS / "TodayWeather" / f"{locale}.lproj" / "InfoPlist.strings"
        write(out, data, changed)
        locales.append({"locale": locale, "source": src, "commit": commit_of(src), "source_sha256": sha256(data),
                        "output": str(out.relative_to(IOS)), "output_sha256": sha256(out.read_bytes()),
                        "value": strings_value(ROOT / src)})
    english = next(l["value"] for l in locales if l["locale"] == "en")

    entry = plugin_lock()
    xml = plugin_xml(entry, args.plugin_tarball)
    ids = plugin_entries(xml)

    block = info_block(english, ids)
    info = INFO.read_text(encoding="utf-8")
    if BEGIN in info:
        start, end = info.index(BEGIN), info.index(END) + len(END)
        info = info[:start] + block + info[end:]
    else:
        tail = "</dict>\n</plist>\n"
        if not info.endswith(tail):
            sys.exit(f"{INFO.relative_to(ROOT)} does not end with </dict></plist>")
        info = info[:-len(tail)] + block + tail
    write(INFO, info.encode("utf-8"), changed)

    provenance = {
        "tool": "ios/tools/import_ad_privacy.py",
        "config": {"source": CONFIG, "commit": commit_of(CONFIG), "sha256": sha256((ROOT / CONFIG).read_bytes())},
        "tracking": locales,
        "plugin": {"package": PLUGIN, "version": entry["version"], "resolved": entry["resolved"],
                   "integrity": entry["integrity"], "lock": LOCK, "lock_commit": commit_of(LOCK),
                   "plugin_xml_sha256": sha256(xml), "GADDelayAppMeasurementInit": True, "SKAdNetworkItems": ids},
        "info_plist": {"output": str(INFO.relative_to(IOS)), "block_sha256": sha256(block.encode("utf-8"))},
    }
    write(PROVENANCE, (json.dumps(provenance, ensure_ascii=False, indent=1) + "\n").encode("utf-8"), changed)
    print("\n".join(f"wrote {c}" for c in changed) if changed else "unchanged")


if __name__ == "__main__":
    main()
