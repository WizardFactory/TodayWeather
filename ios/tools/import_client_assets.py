#!/usr/bin/env python3
"""Copy the Cordova client's images, translations, town list, fonts and icons into the iOS app.

The iOS build never reads client/ (or android/); this tool is the only bridge. It is deterministic:
re-running it without changes in its sources leaves ios/ unchanged.

Outputs (paths relative to ios/):
  Core/Sources/TWResources/Client/img/**          copies of client/www/img/**/*.png
  Core/Sources/TWResources/Client/data/towns.json client/www/data/town.js without its `window.towns=` prefix
  Core/Sources/TWResources/Client/<lproj>/Localizable.strings  client/www/locales/*.json as .strings
  Core/Sources/TWResources/Client/fonts/MaterialIcons-Regular.ttf  client/www/fonts/MaterialIcons-Regular.ttf
  Core/Sources/TWResources/Client/fonts/ionicons.ttf  the Ionicons font of the Cordova build (see below)
  TodayWeather/Assets.xcassets/AppIcon.appiconset/icon-1024.png  client/tw.resources/icon.png (config.xml <icon>)
  TodayWeather/Assets.xcassets/Splash.imageset/splash.png  client/tw.resources/ios/splash/Default@2x~universal~anyany.png
  provenance/client-assets.json  source path, last commit and hashes for every output

Ionicons 2.0.1 ships with Ionic 1.3.5, which Bower installs into client/www/lib outside Git. The Android
import (android/tools/import_cordova_fonts.py) took it from a Cordova build; this tool copies that
committed copy after checking it against the Android provenance record, and records both steps.

Usage: python3 ios/tools/import_client_assets.py   (from anywhere inside the repository; needs full Git history)
"""
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IOS = ROOT / "ios"
CLIENT = ROOT / "client" / "www"
TW_RESOURCES = ROOT / "client" / "tw.resources"
RESOURCES = IOS / "Core" / "Sources" / "TWResources" / "Client"
ASSETS = IOS / "TodayWeather" / "Assets.xcassets"
PROVENANCE = IOS / "provenance" / "client-assets.json"
ANDROID_IONICONS = ROOT / "android" / "app" / "src" / "main" / "res" / "font" / "ionicons.ttf"
ANDROID_FONT_PROVENANCE = ROOT / "android" / "app" / "provenance" / "cordova-fonts.json"

# Cordova registers these catalogs and falls back to English (client/www/js/app.js); must match
# TWResources.catalogs.
LOCALES = {"en": "en", "ko": "ko", "ja": "ja", "de": "de", "zh-CN": "zh-Hans", "zh-TW": "zh-Hant"}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git(*args) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True).stdout


def last_commits(paths):
    """Last commit that touched each path, from one `git log` walk."""
    wanted = {p.relative_to(ROOT).as_posix() for p in paths}
    found, commit = {}, None
    for line in git("log", "--format=@%H", "--name-only", "--", *sorted(wanted)).splitlines():
        if line.startswith("@"):
            commit = line[1:]
        elif line in wanted and line not in found:
            found[line] = commit
    missing = wanted - found.keys()
    if missing:
        sys.exit(f"no commit found for {sorted(missing)[:3]} (needs full history and committed sources)")
    return found


def strings_value(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")


def strings_file(catalog: dict) -> bytes:
    lines = ["/* Generated by ios/tools/import_client_assets.py from client/www/locales; do not edit. */"]
    for key in sorted(catalog):
        if not isinstance(catalog[key], str):
            sys.exit(f"unsupported catalog entry {key!r}")
        lines.append(f'"{strings_value(key)}" = "{strings_value(catalog[key])}";')
    return ("\n".join(lines) + "\n").encode("utf-8")


SKIPPED = []  # tracked duplicates that differ from a kept file only by letter case


def tracked_images():
    """Tracked PNGs from Git, not the file system: case-insensitive checkouts (macOS) hide
    `client/www/img/KR.png`, a same-content duplicate of the `kr.png` the app references."""
    groups = {}
    for row in filter(None, git("ls-files", "-s", "-z", "--", "client/www/img").split("\0")):
        meta, path = row.split("\t", 1)
        if path.endswith(".png"):
            groups.setdefault(path.lower(), []).append((path, meta.split()[1]))
    images = []
    for key, entries in sorted(groups.items()):
        if len(entries) > 1:
            keep = [e for e in entries if e[0] == key]
            if not keep or len({blob for _, blob in entries}) != 1:
                sys.exit(f"case-insensitive name collision with different content: {entries}")
            SKIPPED.extend(sorted(path for path, _ in entries if path != key))
            entries = keep
        images.append(ROOT / entries[0][0])
    return sorted(images)


def android_ionicons_record():
    """The Android copy of the Cordova Ionicons font, checked against its own provenance record."""
    record = next(r for r in json.loads(ANDROID_FONT_PROVENANCE.read_text(encoding="utf-8"))["files"]
                  if r["output"] == "src/main/res/font/ionicons.ttf")
    data = ANDROID_IONICONS.read_bytes()
    if sha256(data) != record["output_sha256"]:
        sys.exit("android ionicons.ttf does not match android/app/provenance/cordova-fonts.json")
    return record, data


def main():
    images = tracked_images()
    town = CLIENT / "data" / "town.js"
    locales = [CLIENT / "locales" / f"{code}.json" for code in LOCALES]
    material_icons = CLIENT / "fonts" / "MaterialIcons-Regular.ttf"
    icon = TW_RESOURCES / "icon.png"
    splash = TW_RESOURCES / "ios" / "splash" / "Default@2x~universal~anyany.png"
    commits = last_commits(images + [town] + locales + [material_icons, icon, splash, ANDROID_IONICONS])

    outputs = []  # (source, output, data, extra)
    for src in images:
        outputs.append((src, RESOURCES / "img" / src.relative_to(CLIENT / "img"), src.read_bytes(), {}))

    text = town.read_text(encoding="utf-8").strip()
    prefix = "window.towns="
    if not text.startswith(prefix):
        sys.exit("unexpected town.js format")
    towns = json.loads(text[len(prefix):].rstrip(";"))
    data = (json.dumps(towns, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    outputs.append((town, RESOURCES / "data" / "towns.json", data, {}))

    for (code, lproj), src in zip(LOCALES.items(), locales):
        catalog = json.loads(src.read_text(encoding="utf-8"))
        outputs.append((src, RESOURCES / f"{lproj}.lproj" / "Localizable.strings", strings_file(catalog), {}))

    outputs.append((material_icons, RESOURCES / "fonts" / "MaterialIcons-Regular.ttf", material_icons.read_bytes(),
                    {"license": "Apache License 2.0 (Material Icons, Google)"}))
    record, ionicons = android_ionicons_record()
    outputs.append((ANDROID_IONICONS, RESOURCES / "fonts" / "ionicons.ttf", ionicons, {
        "origin": record["source"], "origin_apk_sha256": record["apk_sha256"],
        "version": record["version"], "license": record["license"]}))

    # The App Store icon (no alpha channel, as App Store icons require) and the launch image of the
    # Cordova iOS build (client/config.xml <icon> and <splash>).
    outputs.append((icon, ASSETS / "AppIcon.appiconset" / "icon-1024.png", icon.read_bytes(), {}))
    outputs.append((splash, ASSETS / "Splash.imageset" / "splash.png", splash.read_bytes(), {}))

    # Replace the generated trees so files removed from the sources disappear here too.
    shutil.rmtree(RESOURCES, ignore_errors=True)
    records = []
    for src, out, data, extra in outputs:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)
        rel_src = src.relative_to(ROOT).as_posix()
        records.append({
            "source": rel_src,
            "commit": commits[rel_src],
            "source_sha256": sha256(src.read_bytes()),
            "output": out.relative_to(IOS).as_posix(),
            "output_sha256": sha256(data),
            **extra,
        })
    records.sort(key=lambda r: r["output"])
    PROVENANCE.parent.mkdir(parents=True, exist_ok=True)
    PROVENANCE.write_text(json.dumps({
        "tool": "ios/tools/import_client_assets.py",
        "license": "Same repository and license as client/ (TodayWeather, WizardFactory), except the fonts, whose records name their licenses",
        "locales": LOCALES,
        "skipped_case_duplicates": SKIPPED,
        "files": records,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"imported {len(records)} files; provenance in {PROVENANCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
