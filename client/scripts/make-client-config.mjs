// Generates www/client.config.js (ignored by Git) from the legacy release config named by
// TW_ADS_CLIENT_CONFIG plus overrides from client/.env. Without the release file, the
// checked-in template www/client.config.example.js is the base (development build).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { clientDir, isSet, loadEnv, releaseFile } from './env.mjs';

// Keys of retired integrations (UA, AdMob Pro, Airbridge, paid app).
const DROP_KEYS = ['admobProLicense', 'gaIOSKey', 'gaAndroidKey', 'airBridgeToken', 'airBridgeAppId',
    'iOSPaidAppUrl', 'androidPaidAppUrl'];

function readConfig(file) {
    const sandbox = { window: {} };
    vm.runInNewContext(fs.readFileSync(file, 'utf8'), sandbox, { filename: file });
    return sandbox.window.clientConfig || sandbox.window.twClientConfig;
}

const env = loadEnv({ optional: true });
let base = path.join(clientDir, 'www', 'client.config.example.js');
if (isSet(env.TW_ADS_CLIENT_CONFIG) && isSet(env.TW_RELEASE_LOCAL_DIR)) {
    const release = releaseFile(env, 'TW_ADS_CLIENT_CONFIG');
    if (fs.existsSync(release)) {
        base = release;
    } else {
        console.warn(`${release} not found; run "npm run release:fetch". Using the template.`);
    }
} else {
    console.warn('client/.env names no release client config; using the template (development build).');
}

const config = readConfig(base);
for (const key of DROP_KEYS) delete config[key];

const overrides = {
    serverUrl: env.TW_SERVER_URL,
    admobAndroidBannerAdUnit: env.TW_ADMOB_BANNER_ANDROID,
    admobAndroidInterstitialAdUnit: env.TW_ADMOB_INTERSTITIAL_ANDROID,
    admobIOSBannerAdUnit: env.TW_ADMOB_BANNER_IOS,
    admobIOSInterstitialAdUnit: env.TW_ADMOB_INTERSTITIAL_IOS,
};
for (const [key, value] of Object.entries(overrides)) {
    if (isSet(value)) config[key] = value;
}
config.isPaidApp = false;
config.debug = process.argv.includes('--debug');
config.package = 'todayWeather';

const target = path.join(clientDir, 'www', 'client.config.js');
fs.writeFileSync(target, `// Generated by scripts/make-client-config.mjs from ${path.basename(base)}. Do not commit.\n`
    + `window.clientConfig = ${JSON.stringify(config, null, 4)};\n`);
console.log(`wrote www/client.config.js (base: ${path.basename(base)}, debug: ${config.debug})`);
